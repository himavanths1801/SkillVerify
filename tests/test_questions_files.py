# --------------------------------------------------------------------------
# the path filter
# --------------------------------------------------------------------------
@pytest.mark.parametrize("path", [
    "src/app.py", "analysis.py", "queries/report.sql", "web/App.jsx", "lib/util.ts", "main/App.java", "x/y/z.kt",
    "core.c", "include/core.h", "src/core.cpp", "Program.cs", "main.go", "src/lib.rs", "app.rb", "index.php",
    "analysis.r", "run.sh", "Main.scala", "notebooks/explore.ipynb", "pkg/App.TSX",
])
def test_code_files_survive(path):
    assert files.skip_reason(path, 1000) is None


@pytest.mark.parametrize("folder", [
    "node_modules", "vendor", "venv", ".venv", "env", "site-packages", "dist", "build", "target", "out",
    "__pycache__", ".git", "third_party", "bower_components", ".idea", ".vscode", ".gradle", ".next", "coverage"])
def test_every_vendored_or_build_folder_is_junk(folder):
    assert files.skip_reason(f"{folder}/lib/code.py", 1000) == files.JUNK_FOLDER
    assert files.skip_reason(f"app/{folder}/code.py", 1000) == files.JUNK_FOLDER


@pytest.mark.parametrize("path", [
    "app.min.js", "dist.lock", "package-lock.json", "api_pb2.py", "api_pb2_grpc.py", "x.generated.ts",
    "app.bundle.js", "a/b/vendor.min.css"])
def test_generated_names_are_junk(path):
    assert files.skip_reason(path, 1000) in (files.GENERATED, files.NOT_CODE)
    if files.language_of(path):
        assert files.skip_reason(path, 1000) == files.GENERATED


@pytest.mark.parametrize("path", [
    "test/a.py", "tests/a.py", "__tests__/a.js", "spec/a.rb", "e2e/a.ts", "src/tests/a.py", "test_models.py",
    "models_test.py", "app.test.js", "app.spec.ts", "conftest.py", "pkg/conftest.py"])
def test_test_files_are_junk(path):
    assert files.skip_reason(path, 1000) == files.TEST_FILE


@pytest.mark.parametrize("path", [
    ".env", ".env.local", "config/.env.production", "server.pem", "id.key", "id_rsa", "id_rsa.pub", "cert.p12",
    "secrets.py", "secret.json", "credentials.py", "credentials.json", "app/Secrets.ts"])
def test_possible_secret_files_are_junk(path):
    assert files.skip_reason(path, 1000) == files.SECRET_FILE


@pytest.mark.parametrize("path", [
    "README.md", "notes.txt", "data.csv", "config.json", "ci.yml", "ci.yaml", "pyproject.toml", "setup.ini",
    "pom.xml", "index.html", "style.css", "logo.svg", "logo.png", "app.exe", "archive.zip", "Makefile", "Dockerfile",
    "docs/guide.rst"])
def test_non_code_is_never_a_source(path):
    assert files.skip_reason(path, 1000) == files.NOT_CODE


def test_size_window():
    assert files.skip_reason("a.py", config.MIN_FILE_BYTES - 1) == files.TOO_SMALL
    assert files.skip_reason("a.py", config.MIN_FILE_BYTES) is None
    assert files.skip_reason("a.py", config.MAX_FILE_BYTES) is None
    assert files.skip_reason("a.py", config.MAX_FILE_BYTES + 1) == files.TOO_BIG
    assert files.skip_reason("a.py") is None  # no size known: the path alone decides


def test_extension_and_language():
    assert files.extension_of("a/b/C.PY") == ".py" and files.extension_of("Makefile") == ""
    assert files.language_of("x.ipynb") == "python" and files.language_of("x.sql") == "sql"
    assert files.language_of("x.md") is None


