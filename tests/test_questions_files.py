SECRETS = [
    'API_KEY = "abcd1234efgh5678"', "password: 'hunter2hunter2'", 'db_password = "s3cret-pass"',
    'client_secret="topsecretvalue"', "AWS = AKIAIOSFODNN7EXAMPLE", "token = ghp_" + "a" * 30,
    "key = sk-" + "b" * 30, "SECRET_TOKEN = abcdefghijklmnop12345", "g = AIza" + "c" * 35,
    "slack = xoxb-1234567890-abcdef", "pat = github_pat_" + "d" * 30,
]


@pytest.mark.parametrize("line", SECRETS)
def test_secrets_are_redacted(line):
    cleaned = files.redact(f"x = 1\n{line}\ny = 2\n")
    assert files.REDACTED in cleaned and cleaned.startswith("x = 1\n") and cleaned.endswith("y = 2\n")
    for value in ("abcd1234efgh5678", "hunter2hunter2", "s3cret-pass", "topsecretvalue", "AKIAIOSFODNN7EXAMPLE",
                  "abcdefghijklmnop12345"):
        assert value not in cleaned


def test_private_key_blocks_are_redacted():
    block = "-----BEGIN RSA PRIVATE KEY-----\nMIIEow\nabc\n-----END RSA PRIVATE KEY-----"
    assert files.redact(f"a\n{block}\nb") == f"a\n{files.REDACTED}\nb"
    assert files.redact("a\n-----BEGIN PRIVATE KEY-----\nMIIEow\nnever ends") == f"a\n{files.REDACTED}"


def test_normal_code_is_left_alone_and_redaction_is_idempotent():
    assert files.redact(PY_ORDERS) == PY_ORDERS and files.redact(SQL_REPORT) == SQL_REPORT
    assert files.redact("max_tokens = 100\nkey_count = 3\n") == "max_tokens = 100\nkey_count = 3\n"
    once = files.redact("\n".join(SECRETS))
    assert files.redact(once) == once
