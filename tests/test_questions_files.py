# logic score
# --------------------------------------------------------------------------
def test_python_counts_use_ast():
    lines, defs, flow = files.logic_counts(PY_LOGIC_HEAVY, "python")
    assert defs == 4 and flow >= 8 and lines > 30
    assert files.logic_score(PY_LOGIC_HEAVY, "python") > files.logic_score(PY_ORDERS, "python") - 100


def test_unparseable_python_falls_back_to_regexes():
    lines, defs, flow = files.logic_counts("def broken(:\n    if x:\n        for y in z:\n            pass\n", "python")
    assert (defs, flow) == (1, 2) and lines == 4


def test_other_languages_use_regexes():
    sql_defs, sql_flow = files.logic_counts(SQL_REPORT, "sql")[1:]
    assert sql_defs == 1 and sql_flow >= 5  # one CREATE VIEW; JOIN, WHERE, GROUP BY, HAVING ...
    assert files.logic_counts("function a() {}\nconst b = () => 1;\nif (x) {}\n", "javascript")[1:] == (2, 1)
    assert files.logic_counts("release() {\n  git pull\n}\n", "shell")[1] == 1


def test_the_score_is_capped_so_size_alone_cannot_win():
    huge = "\n".join(f"x{i} = {i}" for i in range(5000))
    assert files.logic_score(huge, "python") == config.LOGIC_LINES_CAP
    many_defs = "\n".join(f"def f{i}(): pass" for i in range(200))
    assert files.logic_score(many_defs, "python") <= (
        config.LOGIC_LINES_CAP + config.DEFINITION_WEIGHT * config.DEFINITIONS_CAP)


def test_more_real_logic_scores_higher():
    assert files.logic_score(PY_ORDERS, "python") > files.logic_score("x = 1\n" * 10, "python")


