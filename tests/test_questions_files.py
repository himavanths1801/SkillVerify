def test_python_names_are_exact():
    names, exact = files.defined_names(PY_ORDERS, "python")
    assert exact and {"load_orders", "clean_orders", "OrderReport", "top_customers", "TAX_RATE", "frame",
                      "grouped", "ranked"} <= names
    assert "read_csv" not in names and "pd" not in names


def test_python_assignment_forms_are_names():
    code = "a: int = 1\nb += 2\nfor i, (j, k) in z:\n    pass\nwith open(f) as handle:\n    pass\n(c, d) = 1, 2\n" \
           "[m for n in q]\n"
    names, exact = files.defined_names(code, "python")
    assert exact and {"a", "b", "i", "j", "k", "handle", "c", "d", "n"} <= names


def test_other_languages_are_best_effort():
    names, exact = files.defined_names("function load() {}\nconst go = async () => 1;\nclass Cart {}\n", "javascript")
    assert not exact and {"load", "Cart", "go"} <= names
    sql_names, _ = files.defined_names(SQL_REPORT, "sql")
    assert "monthly_revenue" in sql_names
    java, _ = files.defined_names("public class A {\n  public static int total(int a) {\n    return a;\n  }\n}\n", "java")
    assert {"A", "total"} <= java
    shell, _ = files.defined_names("release() {\n  git pull\n}\n", "shell")
    assert "release" in shell


def test_unparseable_python_gives_a_regex_list():
    names, exact = files.defined_names("def broken(:\n  pass\ndef ok():\n  pass\n", "python")
    assert not exact and "ok" in names


def test_has_definitions():
    assert files.has_definitions(PY_ORDERS, "python")
    assert not files.has_definitions("x = 1\ny = 2\n", "python")
    assert not files.has_definitions("SELECT 1;\n", "sql")
    assert files.has_definitions(SQL_REPORT, "sql")
    assert files.has_definitions("def broken(:\n  pass\n", "python")


