@pytest.mark.parametrize("header", [
    "# This file is auto-generated", "// Autogenerated by tool", "/* Generated by protoc */",
    "# DO NOT EDIT", "-- generated by sqlgen"])
def test_generated_header_is_detected(header):
    assert files.is_generated(f"{header}\nx = 1\n")


def test_generated_notice_after_the_first_lines_is_ignored():
    assert not files.is_generated("a\nb\nc\nd\ne\n# generated by hand\n")
    assert not files.is_generated("import os\n")


def test_notebook_keeps_code_cells_only():
    code = files.notebook_code(NOTEBOOK)
    assert "def simulate" in code and "# Notes" not in code and "OUTPUT-MUST-NOT-APPEAR" not in code
    assert files.notebook_code("not json") == "" and files.notebook_code('{"cells": 5}') == ""
    text = json.dumps({"cells": [{"cell_type": "code", "source": "x = 1"}, "junk"]})
    assert files.notebook_code(text) == "x = 1"


def test_comments_are_not_logic_lines():
    assert files.logic_lines("# c\n\nx = 1\n  # d\n", "python") == 1
    assert files.logic_lines("// c\n/* a\n b */\nint x;\n", "c") == 1
    assert files.logic_lines("-- c\nSELECT 1;\n", "sql") == 1
    assert files.logic_lines("a\nb\n", "unknown-language") == 2
    assert files.strip_comments("x", "unknown-language") == "x"


